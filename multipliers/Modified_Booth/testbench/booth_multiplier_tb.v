`timescale 1ns/1ps

module tb_booth_multiplier;

    // ================================================================
    // Signals
    // ================================================================

    reg clk = 0;
    reg rst;
    reg start;

    reg signed [15:0] multiplicand;
    reg signed [15:0] multiplier;

    wire signed [31:0] product;
    wire done;

    integer errors = 0;
    integer i;

    reg signed [15:0] rand_a;
    reg signed [15:0] rand_b;

    // ================================================================
    // DUT
    // ================================================================

    booth_multiplier DUT (
        .clk          (clk),
        .rst          (rst),
        .start        (start),
        .multiplicand (multiplicand),
        .multiplier   (multiplier),
        .product      (product),
        .done         (done)
    );

    // ================================================================
    // 100 MHz Clock
    // Period = 10 ns
    // ================================================================

    always #5 clk = ~clk;

    // ================================================================
    // Test Task
    // ================================================================

    task run_check;

        input signed [15:0] ma;
        input signed [15:0] mb;

        reg signed [31:0] expected;

        begin

            // --------------------------------------------------------
            // Apply operands while clock is low
            // --------------------------------------------------------

            @(negedge clk);

            multiplicand = ma;
            multiplier   = mb;

            start = 1'b1;

            // --------------------------------------------------------
            // Give DUT one rising edge to capture start and operands
            // --------------------------------------------------------

            @(negedge clk);

            start = 1'b0;

            // --------------------------------------------------------
            // Wait until multiplication is complete
            // --------------------------------------------------------

            wait (done == 1'b1);

            // --------------------------------------------------------
            // Calculate expected result
            // --------------------------------------------------------

            expected = ma * mb;

            // --------------------------------------------------------
            // Compare DUT result with expected result
            // --------------------------------------------------------

            if (product !== expected) begin

                errors = errors + 1;

                $display(
                    "FAIL: %0d * %0d = %0d (expected %0d)",
                    ma,
                    mb,
                    $signed(product),
                    expected
                );

            end

            else begin

                $display(
                    "PASS: %0d * %0d = %0d",
                    ma,
                    mb,
                    $signed(product)
                );

            end

            // --------------------------------------------------------
            // Allow DUT to return to IDLE
            // --------------------------------------------------------

            @(negedge clk);

        end

    endtask

    // ================================================================
    // Test Sequence
    // ================================================================

    initial begin

        // ------------------------------------------------------------
        // Initial conditions
        // ------------------------------------------------------------

        rst          = 1'b1;
        start        = 1'b0;
        multiplicand = 16'sd0;
        multiplier   = 16'sd0;

        // ------------------------------------------------------------
        // Reset
        // ------------------------------------------------------------

        repeat (2)
            @(negedge clk);

        rst = 1'b0;

        // ============================================================
        // BASIC SIGN TESTS
        // ============================================================

        run_check( 16'sd5,  16'sd3);    // +5 × +3 = +15

        run_check(-16'sd5,  16'sd3);    // -5 × +3 = -15

        run_check( 16'sd5, -16'sd3);    // +5 × -3 = -15

        run_check(-16'sd5, -16'sd3);    // -5 × -3 = +15

        // ============================================================
        // ZERO TEST
        // ============================================================

        run_check(16'sd0, 16'sd100);

        run_check(16'sd100, 16'sd0);

        // ============================================================
        // MAXIMUM POSITIVE VALUE
        // ============================================================

        run_check(16'sh7FFF, 16'sd1);

        run_check(16'sh7FFF, 16'sh7FFF);

        // ============================================================
        // MINIMUM NEGATIVE VALUE
        //
        // 16'h8000 = -32768
        // ============================================================

        run_check(16'sh8000, 16'sd1);

        run_check(16'sh8000, -16'sd1);

        // ============================================================
        // MINIMUM × MINIMUM
        //
        // (-32768) × (-32768)
        // = +1073741824
        // = 0x40000000
        // ============================================================

        run_check(16'sh8000, 16'sh8000);

        // ============================================================
        // RANDOM TESTS
        // ============================================================

        for (i = 0; i < 100; i = i + 1) begin

            rand_a = $random;
            rand_b = $random;

            run_check(rand_a, rand_b);

        end

        // ============================================================
        // FINAL RESULT
        // ============================================================

        if (errors == 0) begin

            $display("");
            $display("============================================");
            $display("*** ALL TESTS PASSED ***");
            $display("============================================");

        end

        else begin

            $display("");
            $display("============================================");
            $display("*** %0d TEST(S) FAILED ***", errors);
            $display("============================================");

        end

        $finish;

    end

endmodule